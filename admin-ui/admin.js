async function api(path = "", options = {}) {
  const cookie = document.cookie
    .split(";")
    .map((item) => item.trim())
    .find((item) => item.startsWith(`${context.csrf_cookie}=`));
  const csrf =
    context.csrf_token ||
    (cookie ? decodeURIComponent(cookie.slice(cookie.indexOf("=") + 1)) : "");
  const response = await fetch(base + path, {
    ...options,
    credentials: "same-origin",
    cache: "no-store",
    headers: {
      "Content-Type": "application/json",
      ...(context.csrf_header && csrf ? { [context.csrf_header]: csrf } : {}),
    },
  });
  if (response.status === 401 || response.status === 403) {
    if (!language) installLanguage(navigator.language);
    denied(response.status);
  }
  const value = await response.json().catch(() => null);
  if (!response.ok) {
    const error = new Error(
      typeof value?.detail === "string"
        ? t(value.detail)
        : t("Request failed ({code})", { code: response.status }),
    );
    error.status = response.status;
    throw error;
  }
  if (path === "/context") {
    if (!language)
      installLanguage(
        response.headers.get("Content-Language") || navigator.language,
      );
    const applicationUrl = response.headers.get("X-Netplay-Application-URL");
    if (applicationUrl) value.application_url = applicationUrl;
  }
  return value;
}
function renderResources(value) {
  const percentage = (number) =>
    Number.isFinite(number) ? `${number.toFixed(1)}%` : t("Collecting…");
  const bytes = (number) => {
    if (!Number.isFinite(number)) return "—";
    const units = ["B", "KiB", "MiB", "GiB", "TiB"];
    const index =
      number > 0
        ? Math.min(
            Math.max(0, Math.floor(Math.log(number) / Math.log(1024))),
            units.length - 1,
          )
        : 0;
    return `${(number / 1024 ** index).toFixed(index ? 1 : 0)} ${units[index]}`;
  };
  for (const id of ["service-cpu", "service-memory", "service-network"])
    $(id).textContent = "—";
  for (const id of [
    "service-cpu-detail",
    "service-memory-detail",
    "service-network-detail",
  ])
    $(id).textContent = "";
  $("resource-updated").textContent = value
    ? t("Sampled {time}", {
        time: new Date(value.sampledAt).toLocaleTimeString(language),
      })
    : t("Resource usage is unavailable on this bridge.");
  if (!value) return;
  const { service } = value;
  const scope = service.scope === "container" ? "container" : "process";
  $("service-cpu-label").textContent = t(
    scope === "container" ? "Bridge container CPU" : "Bridge process CPU",
  );
  $("service-memory-label").textContent = t(
    scope === "container" ? "Bridge container memory" : "Bridge process memory",
  );
  $("service-cpu").textContent = percentage(service.cpuPercent);
  $("service-cpu-detail").textContent = t("{cores} CPU capacity", {
    cores: service.cores,
  });
  $("service-memory").textContent = bytes(service.usedBytes);
  $("service-memory-detail").textContent = service.limitBytes
    ? t("{usage} of {limit} limit", {
        usage: percentage(service.memoryPercent),
        limit: bytes(service.limitBytes),
      })
    : t("No container memory limit reported");
  const network = service.network;
  if (!network) {
    $("service-network").textContent = t("Unavailable");
    $("service-network-detail").textContent = t(
      "Container network statistics are unavailable.",
    );
    return;
  }
  const rate = (number) =>
    Number.isFinite(number) ? `${bytes(number)}/s` : t("Collecting…");
  $("service-network").textContent =
    `↓ ${rate(network.rxBytesPerSecond)}\n↑ ${rate(network.txBytesPerSecond)}`;
  $("service-network-detail").textContent = t("Received {rx} · Sent {tx}", {
    rx: bytes(network.rxBytes),
    tx: bytes(network.txBytes),
  });
}
