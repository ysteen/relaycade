let language;
function t(message, values = {}) {
  const text = language === "ko" ? (korean[message] ?? message) : message;
  return text.replace(
    /\{(\w+)\}/g,
    (placeholder, key) => values[key] ?? placeholder,
  );
}

function installLanguage(locale) {
  language = /^ko(?:[-_]|$)/i.test(locale) ? "ko" : "en";
  if (language === "en") return;
  document.documentElement.lang = language;
  const text = document.createTreeWalker(
    document.documentElement,
    NodeFilter.SHOW_TEXT,
  );
  while (text.nextNode()) {
    const node = text.currentNode;
    const key = node.data.trim().replace(/\s+/g, " ");
    if (Object.hasOwn(korean, key)) node.data = t(key);
  }
  for (const element of document.querySelectorAll(
    "[aria-label], [placeholder], [title]",
  )) {
    for (const attribute of ["aria-label", "placeholder", "title"]) {
      const value = element.getAttribute(attribute);
      if (Object.hasOwn(korean, value))
        element.setAttribute(attribute, t(value));
    }
  }
}

