function renderLogs() {
  const query = $("log-search").value.toLowerCase();
  const filtered = logs.filter((entry) =>
    JSON.stringify(entry).toLowerCase().includes(query),
  );
  $("logs-message").textContent = filtered.length
    ? t("{count} events", { count: filtered.length })
    : query
      ? t("No matching events.")
      : t("No bridge events recorded yet.");
  $("log-entries").replaceChildren(
    ...filtered
      .slice()
      .reverse()
      .map((entry) => {
        const row = document.createElement("li"),
          time = document.createElement("time"),
          event = document.createElement("strong"),
          fields = document.createElement("pre");
        time.dateTime = entry.time;
        time.textContent = new Date(entry.time).toLocaleTimeString(language);
        event.textContent = entry.event;
        fields.textContent = JSON.stringify(entry.fields);
        row.append(time, event, fields);
        return row;
      }),
  );
}
async function refreshLogs() {
  const value = await api(`/logs?after=${cursor}`);
  if (logStart !== undefined && logStart !== value.startedAt) {
    logs = [];
    cursor = 0;
    logStart = value.startedAt;
    return refreshLogs();
  }
  logStart = value.startedAt;
  logs = [
    ...new Map(
      [...logs, ...value.events].map((entry) => [entry.id, entry]),
    ).values(),
  ].slice(-500);
  cursor = value.cursor;
  renderLogs();
}
async function checkAccess() {
  $("check-access").disabled = true;
  clearInterval(timer);
  try {
    context = await api("/context");
    for (const [id, text] of [
      ["application-link", "Open {app}"],
      ["signin-link", "Sign in to {app}"],
    ]) {
      $(id).href = context.application_url;
      $(id).textContent = t(text, { app: context.application_name });
    }
    await load(true);
    status(t("Connected to the bridge."));
    timer = setInterval(async () => {
      if (document.hidden || busy) return;
      try {
        await load();
        if (!$("logs-panel").hidden && $("live-logs").checked)
          await refreshLogs();
      } catch (error) {
        $("bridge-status").textContent = t("Unavailable");
        status(error.message, true);
      }
    }, 5000);
  } catch (error) {
    if (!language) installLanguage(navigator.language);
    if (error.status !== 401 && error.status !== 403)
      $("access-message").textContent = error.message;
    status(error.message, true);
  } finally {
    $("check-access").disabled = false;
  }
}
async function action(button, operation, message) {
  if (busy) return;
  busy = true;
  button.disabled = true;
  try {
    await operation();
    await load();
    status(t(message));
  } catch (error) {
    status(error.message, true);
  } finally {
    busy = false;
    button.disabled = false;
  }
}
